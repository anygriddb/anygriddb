import { describe, expect, it } from "vitest";
import {
  buildCreateHome,
  buildDropHome,
  buildDropHomeColumn,
  buildDropHomeTable,
  buildHomeColumn,
  buildHomeColumnExists,
  buildHomeTable,
  homeSchemaName,
  homeTableName,
  isHomeTable,
} from "./home";

const BASE = "01a1c9c4-90ed-7f2c-b364-428dbed4bbbc";
const SCHEMA = "ag01a1c9c490ed7f2cb364428dbe";
const TABLE = `t${"a".repeat(26)}`;

describe("a base held in a SQL source", () => {
  it("names its schema from the base and creates it on each engine", () => {
    expect(homeSchemaName(BASE)).toBe(SCHEMA);
    expect(buildCreateHome("postgres", SCHEMA).text).toBe(
      `create schema "${SCHEMA}"`,
    );
    expect(buildCreateHome("mysql", SCHEMA).text).toBe(
      `create database "${SCHEMA}"`,
    );
    expect(buildCreateHome("sqlserver", SCHEMA).text).toBe(
      `exec(N'create schema "${SCHEMA}"')`,
    );
  });

  it("types a number to keep its decimals on every engine", () => {
    const columns = [
      { name: "total", fieldType: "number" as const },
      { name: "note", fieldType: "long_text" as const },
    ];
    expect(buildHomeTable("postgres", SCHEMA, TABLE, columns).text).toBe(
      `create table "${SCHEMA}"."${TABLE}" ("id" bigint generated by default as identity primary key, "total" numeric null, "note" text null)`,
    );
    // A bare numeric or decimal keeps no decimal on these engines.
    for (const dialect of ["mysql", "mariadb", "sqlserver"] as const) {
      expect(buildHomeTable(dialect, SCHEMA, TABLE, columns).text).toContain(
        `"total" decimal(38,10) null`,
      );
    }
    expect(
      buildHomeColumn("sqlserver", SCHEMA, TABLE, {
        name: "when",
        fieldType: "datetime",
      }).text,
    ).toBe(`alter table "${SCHEMA}"."${TABLE}" add "when" datetime2(7) null`);
  });

  it("drops what it made, and a missing one is not an error", () => {
    expect(buildDropHomeTable(SCHEMA, TABLE).text).toBe(
      `drop table if exists "${SCHEMA}"."${TABLE}"`,
    );
    expect(buildDropHomeColumn("postgres", SCHEMA, TABLE, "total").text).toBe(
      `alter table "${SCHEMA}"."${TABLE}" drop column if exists "total"`,
    );
    // MySQL has no `if exists` here: the caller asks first.
    expect(buildDropHomeColumn("mysql", SCHEMA, TABLE, "total").text).toBe(
      `alter table "${SCHEMA}"."${TABLE}" drop column "total"`,
    );
    expect(buildHomeColumnExists(SCHEMA, TABLE, "total").values).toEqual([
      SCHEMA,
      TABLE,
      "total",
    ]);
    expect(buildDropHome("postgres", SCHEMA).text).toBe(
      `drop schema if exists "${SCHEMA}" cascade`,
    );
    expect(buildDropHome("sqlserver", SCHEMA).text).toContain(
      `drop schema "${SCHEMA}"`,
    );
  });

  it("refuses a name it did not mint", () => {
    expect(() => buildCreateHome("postgres", "public")).toThrow();
    expect(() => buildDropHome("mysql", "ag")).toThrow();
    expect(() => buildDropHomeTable(SCHEMA, "orders")).toThrow();
    expect(() =>
      buildHomeColumn("postgres", SCHEMA, TABLE, {
        name: 'x"; drop table y; --',
        fieldType: "text",
      }),
    ).toThrow();
    expect(() => homeTableName("not hex at all")).toThrow();
  });

  it("tells a table of such a base from a client's table", () => {
    expect(isHomeTable({ storage: "external", physicalName: "h_ab" })).toBe(
      true,
    );
    expect(isHomeTable({ storage: "external", physicalName: "x_ab" })).toBe(
      false,
    );
    expect(isHomeTable({ storage: "native", physicalName: "h_ab" })).toBe(
      false,
    );
  });
});
