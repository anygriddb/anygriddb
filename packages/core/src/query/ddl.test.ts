import { describe, expect, it } from "vitest";
import {
  buildAddColumn,
  buildConversionStatements,
  buildCreateJunction,
  buildCreateTable,
  buildForeignKeyIndex,
  convertExpression,
  indexName,
  isMetadataConversion,
  sqlLiteral,
} from "./ddl";

describe("DDL", () => {
  it("creates system columns, the sequence index, and both triggers", () => {
    const statements = buildCreateTable({
      table: "t_orders",
      columns: [
        { name: "title", fieldType: "text" },
        { name: "tags", fieldType: "multi_select" },
        { name: "total", fieldType: "formula" },
      ],
    });
    expect(statements).toHaveLength(4);
    expect(statements[0]?.text).toContain(
      `"ag_seq" bigint generated by default as identity`,
    );
    expect(statements[0]?.text).toContain(`"tags" text[]`);
    expect(statements[0]?.text).not.toContain(`"total"`);
    expect(statements[2]?.text).toContain("execute function ag_stamp()");
    expect(statements[3]?.text).toContain("execute function audit_record()");
  });

  it("escapes defaults and refuses reserved or computed columns", () => {
    expect(sqlLiteral("it's \\ ok")).toBe("E'it\\'s \\\\ ok'");
    expect(
      buildAddColumn({
        table: "t_x",
        column: { name: "note", fieldType: "text" },
        defaultValue: "a'b",
      }).text,
    ).toBe(`alter table "t_x" add column "note" text default E'a\\'b'::text`);
    expect(() =>
      buildAddColumn({
        table: "t_x",
        column: { name: "ag_x", fieldType: "text" },
      }),
    ).toThrow("Duplicate column");
    expect(() =>
      buildAddColumn({
        table: "t_x",
        column: { name: "f", fieldType: "formula" },
      }),
    ).toThrow("Invalid column");
    expect(() => sqlLiteral("a\u0000")).toThrow("Invalid default");
  });

  it("converts through safe expressions", () => {
    expect(isMetadataConversion("text", "single_select")).toBe(true);
    expect(isMetadataConversion("text", "number")).toBe(false);
    expect(convertExpression("text", "number", `"x"`)).toBe(
      `ag_try_numeric("x")`,
    );
    expect(convertExpression("single_select", "multi_select", `"x"`)).toContain(
      "string_to_array",
    );
    const conversion = buildConversionStatements({
      table: "t_x",
      column: "x",
      from: "text",
      to: "date",
    });
    expect(conversion.rewrite.text).toBe(
      `update "t_x" set "ag_tmp_x" = ag_try_date("x") where "x" is not null`,
    );
    expect(() => convertExpression("attachment", "text", `"x"`)).toThrow(
      "Invalid conversion",
    );
  });

  it("creates a junction with a right_id index for inverse lookups", () => {
    const statements = buildCreateJunction({
      junction: "j_links",
      leftTable: "t_left",
      rightTable: "t_right",
    });
    expect(statements).toHaveLength(2);
    expect(statements[0]?.text).toContain('create table "j_links"');
    expect(statements[0]?.text).toContain(
      'primary key ("left_id", "right_id")',
    );
    expect(statements[1]?.text).toMatch(
      /create index .* on "j_links" \("right_id"\)/,
    );
    expect(() =>
      buildCreateJunction({
        junction: "Bad-Name",
        leftTable: "t_left",
        rightTable: "t_right",
      }),
    ).toThrow("Invalid table name");
  });

  it("indexes a link's foreign key column", () => {
    const table = "t_0123456789abcdef0123456789abcdef";
    expect(buildForeignKeyIndex({ table, column: "project" }).text).toBe(
      `create index "${indexName(table, "project", "ix")}" on "${table}" ("project")`,
    );
    // The name the migration for existing links computes in SQL.
    expect(indexName(table, "project", "ix")).toBe(
      "ix_0123456789abcdef_f4bd82be",
    );
    expect(() => buildForeignKeyIndex({ table, column: "ag_seq" })).toThrow();
    expect(() =>
      buildForeignKeyIndex({ table: "Bad-Name", column: "project" }),
    ).toThrow("Invalid table name");
  });
});
