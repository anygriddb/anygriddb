import {
  hasPhysicalColumn,
  isWritableType,
  physicalSqlType,
  type FieldType,
} from "../field-types";
import { isReservedColumnName } from "../names";
import { assertIdentifier, quoteIdent, type ParameterizedSql } from "./params";
import { AppError } from "../errors";

/**
 * DDL builders. Utility statements cannot take bind parameters, so every
 * identifier is checked and every default literal is escaped here.
 */

function statement(text: string): ParameterizedSql {
  return { text, values: [] };
}

/** Escaped SQL literal for a DDL default. Rejects NUL. */
export function sqlLiteral(value: string | number | boolean): string {
  if (typeof value === "boolean") {
    return value ? "true" : "false";
  }
  if (typeof value === "number") {
    if (!Number.isFinite(value)) {
      throw new AppError("invalid_default");
    }
    return `'${String(value)}'`;
  }
  if (value.includes("\u0000")) {
    throw new AppError("invalid_default");
  }
  return `E'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

function fnv(value: string): string {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

/** Short deterministic index name for a table column. */
export function indexName(
  table: string,
  column: string,
  kind: "uq" | "ix",
): string {
  return `${kind}_${table.slice(2, 18)}_${fnv(column)}`;
}

export type DdlColumn = { name: string; fieldType: FieldType };

function assertUserColumn(name: string): void {
  assertIdentifier(name, "column name");
  if (isReservedColumnName(name)) {
    throw new AppError("duplicate_column");
  }
}

function columnDefinition(column: DdlColumn): string {
  return `${quoteIdent(column.name)} ${physicalSqlType(column.fieldType)}`;
}

/**
 * Statements that create a physical table: identity, status, system
 * columns, the stored user columns, the sequence index, and both triggers.
 */
export function buildCreateTable(input: {
  table: string;
  columns: readonly DdlColumn[];
}): ParameterizedSql[] {
  assertIdentifier(input.table, "table name");
  if (input.columns.length > 200) {
    throw new AppError("invalid_column_count");
  }
  const seen = new Set<string>();
  const lines = [
    `"id" uuid primary key default ag_uuidv7()`,
    `"ag_status" text not null default 'draft' check ("ag_status" in ('draft', 'submitted', 'locked', 'signed'))`,
    `"ag_seq" bigint generated by default as identity`,
    `"ag_created_at" timestamptz not null default now()`,
    `"ag_updated_at" timestamptz not null default now()`,
    `"ag_created_by" uuid`,
    `"ag_updated_by" uuid`,
  ];
  for (const column of input.columns) {
    assertUserColumn(column.name);
    if (seen.has(column.name)) {
      throw new AppError("duplicate_column");
    }
    seen.add(column.name);
    if (!isWritableType(column.fieldType)) {
      continue;
    }
    lines.push(columnDefinition(column));
  }
  const table = quoteIdent(input.table);
  return [
    statement(`create table ${table} (${lines.join(", ")})`),
    statement(
      `create unique index ${quoteIdent(indexName(input.table, "ag_seq", "ix"))} on ${table} ("ag_seq")`,
    ),
    buildStampTrigger(input.table),
    buildAuditTrigger(input.table),
  ];
}

export function buildAuditTrigger(table: string): ParameterizedSql {
  assertIdentifier(table, "table name");
  return statement(
    `create trigger audit_record after insert or update or delete on ${quoteIdent(table)} for each row execute function audit_record()`,
  );
}

export function buildStampTrigger(table: string): ParameterizedSql {
  assertIdentifier(table, "table name");
  return statement(
    `create trigger ag_stamp before insert or update on ${quoteIdent(table)} for each row execute function ag_stamp()`,
  );
}

export function buildAddColumn(input: {
  table: string;
  column: DdlColumn;
  defaultValue?: string | number | boolean;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertUserColumn(input.column.name);
  if (!isWritableType(input.column.fieldType)) {
    throw new AppError("invalid_column");
  }
  const fallback =
    input.defaultValue === undefined
      ? ""
      : ` default ${sqlLiteral(input.defaultValue)}::${physicalSqlType(input.column.fieldType)}`;
  return statement(
    `alter table ${quoteIdent(input.table)} add column ${columnDefinition(input.column)}${fallback}`,
  );
}

export function buildSetDefault(input: {
  table: string;
  column: DdlColumn;
  defaultValue: string | number | boolean | null;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertUserColumn(input.column.name);
  const target = `alter table ${quoteIdent(input.table)} alter column ${quoteIdent(input.column.name)}`;
  if (input.defaultValue === null) {
    return statement(`${target} drop default`);
  }
  return statement(
    `${target} set default ${sqlLiteral(input.defaultValue)}::${physicalSqlType(input.column.fieldType)}`,
  );
}

export function buildDropColumn(input: {
  table: string;
  column: string;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertIdentifier(input.column, "column name");
  return statement(
    `alter table ${quoteIdent(input.table)} drop column if exists ${quoteIdent(input.column)}`,
  );
}

export function buildRenameColumn(input: {
  table: string;
  from: string;
  to: string;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertIdentifier(input.from, "column name");
  assertIdentifier(input.to, "column name");
  return statement(
    `alter table ${quoteIdent(input.table)} rename column ${quoteIdent(input.from)} to ${quoteIdent(input.to)}`,
  );
}

export function buildDropTable(table: string): ParameterizedSql {
  assertIdentifier(table, "table name");
  return statement(`drop table if exists ${quoteIdent(table)}`);
}

export function buildUniqueIndex(input: {
  table: string;
  column: string;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertUserColumn(input.column);
  return statement(
    `create unique index ${quoteIdent(indexName(input.table, input.column, "uq"))} on ${quoteIdent(input.table)} (${quoteIdent(input.column)})`,
  );
}

export function buildDropUniqueIndex(input: {
  table: string;
  column: string;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertIdentifier(input.column, "column name");
  return statement(
    `drop index if exists ${quoteIdent(indexName(input.table, input.column, "uq"))}`,
  );
}

/** Adds a nullable foreign key. The target table must already exist. */
export function buildAddForeignKeyColumn(input: {
  table: string;
  column: string;
  targetTable: string;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertUserColumn(input.column);
  assertIdentifier(input.targetTable, "table name");
  return statement(
    `alter table ${quoteIdent(input.table)} add column ${quoteIdent(input.column)} uuid references ${quoteIdent(input.targetTable)} ("id") on delete set null`,
  );
}

/** Junction of row ids. Both sides cascade when a row is removed. */
/**
 * Many-to-many junction: primary key covers left→right lookups; a second
 * index on `right_id` covers inverse (right→left) scans used by link
 * columns that point the other way.
 */
export function buildCreateJunction(input: {
  junction: string;
  leftTable: string;
  rightTable: string;
}): ParameterizedSql[] {
  assertIdentifier(input.junction, "table name");
  assertIdentifier(input.leftTable, "table name");
  assertIdentifier(input.rightTable, "table name");
  const table = quoteIdent(input.junction);
  return [
    statement(
      `create table ${table} ("left_id" uuid not null references ${quoteIdent(input.leftTable)} ("id") on delete cascade, "right_id" uuid not null references ${quoteIdent(input.rightTable)} ("id") on delete cascade, primary key ("left_id", "right_id"))`,
    ),
    statement(
      `create index ${quoteIdent(indexName(input.junction, "right_id", "ix"))} on ${table} ("right_id")`,
    ),
  ];
}

const TEXT_SQL = new Set(["text"]);

/** True when both types share a SQL type, so conversion only touches the catalog. */
export function isMetadataConversion(from: FieldType, to: FieldType): boolean {
  if (!isWritableType(from) || !isWritableType(to)) {
    return false;
  }
  return physicalSqlType(from) === physicalSqlType(to);
}

const CONVERTIBLE: ReadonlySet<FieldType> = new Set([
  "text",
  "long_text",
  "email",
  "url",
  "phone",
  "single_select",
  "multi_select",
  "number",
  "rating",
  "duration",
  "boolean",
  "date",
  "datetime",
]);

export function isConvertible(from: FieldType, to: FieldType): boolean {
  return from !== to && CONVERTIBLE.has(from) && CONVERTIBLE.has(to);
}

/**
 * Expression that converts `source` (a column reference) from one type to
 * another without raising: values that do not fit become null.
 */
export function convertExpression(
  from: FieldType,
  to: FieldType,
  source: string,
): string {
  if (!isConvertible(from, to)) {
    throw new AppError("invalid_conversion");
  }
  const fromSql = physicalSqlType(from);
  const toSql = physicalSqlType(to);
  const asText =
    fromSql === "text"
      ? source
      : fromSql === "text[]"
        ? `array_to_string(${source}, ', ')`
        : fromSql === "numeric"
          ? `trim_scale(${source})::text`
          : fromSql === "date"
            ? `to_char(${source}, 'YYYY-MM-DD')`
            : fromSql === "timestamptz"
              ? `to_char(${source} at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')`
              : `${source}::text`;
  switch (toSql) {
    case "text":
      return TEXT_SQL.has(fromSql) ? source : asText;
    case "text[]":
      return fromSql === "text"
        ? `(case when ${source} is null or btrim(${source}) = '' then null else array(select distinct btrim(v) from unnest(string_to_array(${source}, ',')) v where btrim(v) <> '') end)`
        : `(case when ${source} is null then null else array[${asText}] end)`;
    case "numeric":
      if (fromSql === "boolean") {
        return `(case when ${source} then 1 when not ${source} then 0 end)::numeric`;
      }
      if (fromSql === "date" || fromSql === "timestamptz") {
        return "null::numeric";
      }
      return `ag_try_numeric(${asText})`;
    case "boolean":
      if (fromSql === "numeric") {
        return `(${source} <> 0)`;
      }
      return `(case when lower(btrim(${asText})) in ('true', 'yes', 'y', '1', 'x', 'oui', 'vrai', 'checked') then true when ${asText} is null then null else false end)`;
    case "date":
      if (fromSql === "timestamptz") {
        return `(${source} at time zone 'UTC')::date`;
      }
      return `ag_try_date(${asText})`;
    case "timestamptz":
      if (fromSql === "date") {
        return `(${source}::timestamp at time zone 'UTC')`;
      }
      return `ag_try_timestamptz(${asText})`;
    default:
      throw new AppError("invalid_conversion");
  }
}

/**
 * Data-rewriting conversion through a temporary column. The UPDATE runs
 * under the row audit trigger, so locked or signed rows make it fail.
 */
export function buildConversionStatements(input: {
  table: string;
  column: string;
  from: FieldType;
  to: FieldType;
}): {
  prepare: ParameterizedSql[];
  rewrite: ParameterizedSql;
  finish: ParameterizedSql[];
} {
  assertIdentifier(input.table, "table name");
  assertUserColumn(input.column);
  if (!hasPhysicalColumn(input.from) || !isWritableType(input.to)) {
    throw new AppError("invalid_conversion");
  }
  const temp = `ag_tmp_${input.column}`.slice(0, 63);
  const table = quoteIdent(input.table);
  return {
    prepare: [
      statement(
        `alter table ${table} add column ${quoteIdent(temp)} ${physicalSqlType(input.to)}`,
      ),
    ],
    rewrite: statement(
      `update ${table} set ${quoteIdent(temp)} = ${convertExpression(input.from, input.to, quoteIdent(input.column))} where ${quoteIdent(input.column)} is not null`,
    ),
    finish: [
      buildDropColumn({ table: input.table, column: input.column }),
      statement(
        `alter table ${table} rename column ${quoteIdent(temp)} to ${quoteIdent(input.column)}`,
      ),
    ],
  };
}

/** Counts and samples what a conversion would keep, without changing anything. */
export function buildConversionPreview(input: {
  table: string;
  column: string;
  from: FieldType;
  to: FieldType;
}): ParameterizedSql {
  assertIdentifier(input.table, "table name");
  assertIdentifier(input.column, "column name");
  const column = quoteIdent(input.column);
  const table = quoteIdent(input.table);
  const expression = convertExpression(input.from, input.to, column);
  return statement(
    `select count(*)::int as "total", count(*) filter (where (${expression}) is null)::int as "lost", (select jsonb_agg(jsonb_build_object('before', to_jsonb(s."v"), 'after', to_jsonb(s."c"))) from (select ${column} as "v", ${expression} as "c" from ${table} where ${column} is not null limit 5) s) as "samples" from ${table} where ${column} is not null`,
  );
}
