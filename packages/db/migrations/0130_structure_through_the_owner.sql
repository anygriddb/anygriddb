CREATE FUNCTION ag_create_junction(junction text, left_table text, right_table text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  PERFORM ag_assert_table_name(junction);
  PERFORM ag_assert_table_name(left_table);
  PERFORM ag_assert_table_name(right_table);
  EXECUTE format(
    'CREATE TABLE %I ("left_id" uuid NOT NULL REFERENCES %I ("id") ON DELETE CASCADE, '
    || '"right_id" uuid NOT NULL REFERENCES %I ("id") ON DELETE CASCADE, '
    || 'PRIMARY KEY ("left_id", "right_id"))',
    junction, left_table, right_table
  );
  EXECUTE format('CREATE INDEX %I ON %I ("right_id")', ag_index_name(junction, 'right_id', 'ix'), junction);
END;
$$;--> statement-breakpoint
-- A field's conversion: the column it fills, the column that marks the rows
-- it changes, the guard that keeps writers out, and the switch.
CREATE FUNCTION ag_conversion_add_column(tbl text, col text, field_type text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  PERFORM ag_assert_table_name(tbl);
  PERFORM ag_assert_field_column(col);
  EXECUTE format('ALTER TABLE %I ADD COLUMN %I %s', tbl, left('ag_tmp_' || col, 63), ag_field_sql_type(field_type));
END;
$$;--> statement-breakpoint
