CREATE FUNCTION ag_conversion_guard(tbl text, job text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  PERFORM ag_assert_table_name(tbl);
  IF job IS NULL OR job !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
    RAISE EXCEPTION 'Invalid job';
  END IF;
  EXECUTE format(
    'CREATE TRIGGER ag_converting BEFORE INSERT OR UPDATE OR DELETE ON %I '
    || 'FOR EACH STATEMENT EXECUTE FUNCTION ag_refuse_while_converting(%L)',
    tbl, job
  );
END;
$$;--> statement-breakpoint
CREATE FUNCTION ag_conversion_drop_guard(tbl text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
