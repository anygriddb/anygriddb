-- What the application changes in the structure of its tables goes through
-- these functions of the owner (ADR 0119): the role it will sign in as owns no
-- table, since the owner of a table can rewrite it with no trigger firing.
-- Each takes names and field types, never a statement, and checks them here
-- whatever the caller did: only a table of rows, never a system column.
-- PostgreSQL searches pg_catalog first when the path does not name it, and
-- what these functions create goes to the first schema named: `public`.
CREATE FUNCTION ag_assert_table_name(tbl text)
RETURNS void
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog
AS $$
BEGIN
  IF tbl IS NULL OR length(tbl) > 63 OR tbl !~ '^[tj]_[a-z0-9_]+$' THEN
    RAISE EXCEPTION 'Invalid table name';
  END IF;
END;
$$;--> statement-breakpoint
CREATE FUNCTION ag_assert_field_column(col text)
RETURNS void
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog
AS $$
BEGIN
  IF col IS NULL OR length(col) > 63 OR col !~ '^[a-z_][a-z0-9_]*$'
    OR col = 'id' OR left(col, 3) = 'ag_' THEN
    RAISE EXCEPTION 'Invalid column name';
  END IF;
END;
$$;--> statement-breakpoint
CREATE FUNCTION ag_field_sql_type(field_type text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog
AS $$
BEGIN
  CASE field_type
    WHEN 'text', 'long_text', 'email', 'url', 'phone', 'color', 'place',
         'single_select' THEN RETURN 'text';
    WHEN 'json' THEN RETURN 'jsonb';
    WHEN 'number', 'rating', 'duration' THEN RETURN 'numeric';
    WHEN 'boolean' THEN RETURN 'boolean';
    WHEN 'date' THEN RETURN 'date';
    WHEN 'datetime' THEN RETURN 'timestamptz';
    WHEN 'multi_select', 'attachment' THEN RETURN 'text[]';
    WHEN 'user' THEN RETURN 'uuid[]';
    WHEN 'relation_one_to_many' THEN RETURN 'uuid';
    ELSE RAISE EXCEPTION 'Invalid column';
  END CASE;
END;
$$;--> statement-breakpoint
-- The name `indexName` gives in `packages/core/src/query/ddl.ts`.
CREATE FUNCTION ag_index_name(tbl text, col text, kind text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog
AS $$
DECLARE
  hash bigint := 2166136261;
BEGIN
  IF kind NOT IN ('uq', 'ix', 'gin') THEN
    RAISE EXCEPTION 'Invalid index';
  END IF;
  FOR i IN 1..length(col) LOOP
    hash := ((hash # ascii(substr(col, i, 1))) * 16777619) % 4294967296;
  END LOOP;
  RETURN kind || '_' || substr(tbl, 3, 16) || '_' || lpad(to_hex(hash), 8, '0');
END;
$$;--> statement-breakpoint
CREATE FUNCTION ag_create_table(tbl text, columns text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  fields jsonb := columns::jsonb;
  field jsonb;
  defs text := '';
BEGIN
  PERFORM ag_assert_table_name(tbl);
  IF jsonb_typeof(fields) <> 'array' OR jsonb_array_length(fields) > 200 THEN
    RAISE EXCEPTION 'Invalid column count';
  END IF;
  FOR field IN SELECT value FROM jsonb_array_elements(fields) LOOP
    PERFORM ag_assert_field_column(field->>'name');
    defs := defs || format(', %I %s', field->>'name', ag_field_sql_type(field->>'fieldType'));
  END LOOP;
  EXECUTE format(
    'CREATE TABLE %I ("id" uuid PRIMARY KEY DEFAULT ag_uuidv7(), '
    || '"ag_status" text NOT NULL DEFAULT ''draft'' CHECK ("ag_status" IN (''draft'', ''submitted'', ''locked'', ''signed'')), '
    || '"ag_seq" bigint GENERATED BY DEFAULT AS IDENTITY, '
    || '"ag_position" numeric NOT NULL DEFAULT nextval(''ag_row_position''), '
    || '"ag_created_at" timestamptz NOT NULL DEFAULT now(), '
    || '"ag_updated_at" timestamptz NOT NULL DEFAULT now(), '
    || '"ag_created_by" uuid, "ag_updated_by" uuid%s)',
    tbl, defs
  );
  EXECUTE format('CREATE UNIQUE INDEX %I ON %I ("ag_seq")', ag_index_name(tbl, 'ag_seq', 'ix'), tbl);
  EXECUTE format('CREATE INDEX %I ON %I ("ag_position", "ag_seq")', ag_index_name(tbl, 'ag_position', 'ix'), tbl);
  FOR field IN SELECT value FROM jsonb_array_elements(fields) WHERE value->>'fieldType' = 'attachment' LOOP
    EXECUTE format('CREATE INDEX %I ON %I USING gin (%I)', ag_index_name(tbl, field->>'name', 'gin'), tbl, field->>'name');
  END LOOP;
  EXECUTE format('CREATE TRIGGER ag_stamp BEFORE INSERT OR UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION ag_stamp()', tbl);
  EXECUTE format('CREATE TRIGGER audit_record AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION audit_record()', tbl);
END;
$$;--> statement-breakpoint
CREATE FUNCTION ag_add_column(tbl text, col text, field_type text, default_value text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  sql_type text := ag_field_sql_type(field_type);
BEGIN
  PERFORM ag_assert_table_name(tbl);
  PERFORM ag_assert_field_column(col);
  EXECUTE format('ALTER TABLE %I ADD COLUMN %I %s', tbl, col, sql_type)
    || CASE WHEN default_value IS NULL THEN ''
       ELSE format(' DEFAULT %L::%s', default_value, sql_type) END;
END;
$$;--> statement-breakpoint
CREATE FUNCTION ag_set_column_default(tbl text, col text, field_type text, default_value text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  PERFORM ag_assert_table_name(tbl);
  PERFORM ag_assert_field_column(col);
  IF default_value IS NULL THEN
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I DROP DEFAULT', tbl, col);
  ELSE
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET DEFAULT %L::%s', tbl, col, default_value, ag_field_sql_type(field_type));
  END IF;
END;
$$;--> statement-breakpoint
