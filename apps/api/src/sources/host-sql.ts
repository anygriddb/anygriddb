/**
 * A base whose tables are created in a SQL source (a schema of its own).
 * The statements are the product's, the identifiers are its own, and a
 * table that already existed at the client is never one of these.
 */
import {
  AppError,
  type FieldType,
  type SqlSourceEngine,
} from "@anygriddb/core";

const SCHEMA = /^ag[0-9a-f]{26}$/;
const TABLE = /^t[0-9a-f]{26}$/;
const COLUMN = /^[a-z_][a-z0-9_]{0,62}$/;

/** The schema name of a base: stable, short enough for every engine. */
export function homeSchemaName(baseId: string): string {
  const name = `ag${baseId.replaceAll("-", "").slice(0, 26)}`;
  return schemaOf(name);
}

/** The table name in that schema: not the person's label. */
export function homeTableName(): string {
  const name = `t${crypto.randomUUID().replaceAll("-", "").slice(0, 26)}`;
  return tableOf(name);
}

function schemaOf(name: string): string {
  if (!SCHEMA.test(name)) throw new AppError("invalid_arguments");
  return name;
}

function tableOf(name: string): string {
  if (!TABLE.test(name)) throw new AppError("invalid_arguments");
  return name;
}

function columnOf(name: string): string {
  if (!COLUMN.test(name)) throw new AppError("invalid_arguments");
  return name;
}

function quoted(engine: SqlSourceEngine, name: string): string {
  if (engine === "mysql" || engine === "mariadb") return `\`${name}\``;
  if (engine === "sqlserver") return `[${name}]`;
  return `"${name}"`;
}

/** Creates the schema the base's tables will live in. Oracle uses the account's own. */
export function createHomeSql(
  engine: SqlSourceEngine,
  schema: string,
): string | null {
  const name = schemaOf(schema);
  switch (engine) {
    case "postgres":
      return `CREATE SCHEMA ${quoted(engine, name)}`;
    case "mysql":
    case "mariadb":
      return `CREATE DATABASE ${quoted(engine, name)}`;
    case "sqlserver":
      return `IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = N'${name}') EXEC(N'CREATE SCHEMA ${name}')`;
    case "oracle":
      return null;
  }
}

function columnType(engine: SqlSourceEngine, fieldType: FieldType): string {
  switch (fieldType) {
    case "number":
    case "rating":
    case "duration":
      return engine === "oracle" ? "number" : "numeric";
    case "boolean":
      return engine === "sqlserver" ? "bit" : "boolean";
    case "date":
      return "date";
    case "datetime":
    case "created_time":
    case "last_modified_time":
      if (engine === "sqlserver") return "datetime2";
      if (engine === "oracle") return "timestamp";
      return engine === "postgres" ? "timestamptz" : "datetime(6)";
    case "json":
      if (engine === "postgres") return "jsonb";
      if (engine === "oracle") return "clob";
      if (engine === "sqlserver") return "nvarchar(max)";
      return "json";
    case "long_text":
      if (engine === "sqlserver") return "nvarchar(max)";
      if (engine === "oracle") return "clob";
      return "text";
    default:
      if (engine === "sqlserver") return "nvarchar(4000)";
      if (engine === "oracle") return "varchar2(4000)";
      return "text";
  }
}

/** A table AnyGridDB creates in the schema it owns, with an identity id. */
export function createHomeTableSql(
  engine: SqlSourceEngine,
  schema: string,
  table: string,
  columns: readonly { name: string; fieldType: FieldType }[],
): string {
  const id =
    engine === "mysql" || engine === "mariadb"
      ? `${quoted(engine, columnOf("id"))} bigint primary key auto_increment`
      : engine === "sqlserver"
        ? `${quoted(engine, columnOf("id"))} bigint identity primary key`
        : engine === "oracle"
          ? `${quoted(engine, columnOf("id"))} number generated by default as identity primary key`
          : `${quoted(engine, columnOf("id"))} bigint generated by default as identity primary key`;
  const lines = [
    id,
    ...columns.map(
      (column) =>
        `${quoted(engine, columnOf(column.name))} ${columnType(engine, column.fieldType)}`,
    ),
  ];
  return `CREATE TABLE ${quoted(engine, schemaOf(schema))}.${quoted(engine, tableOf(table))} (${lines.join(", ")})`;
}

/** Drops one table this product created. A missing table is not an error. */
export function dropHomeTableSql(
  engine: SqlSourceEngine,
  schema: string,
  table: string,
): string {
  return `DROP TABLE IF EXISTS ${quoted(engine, schemaOf(schema))}.${quoted(engine, tableOf(table))}`;
}

/** Drops the schema. A missing schema is not an error. Oracle is refused. */
export function dropHomeSql(
  engine: SqlSourceEngine,
  schema: string,
): string | null {
  const name = schemaOf(schema);
  switch (engine) {
    case "postgres":
      return `DROP SCHEMA IF EXISTS ${quoted(engine, name)} CASCADE`;
    case "mysql":
    case "mariadb":
      return `DROP DATABASE IF EXISTS ${quoted(engine, name)}`;
    case "sqlserver":
      return `IF EXISTS (SELECT 1 FROM sys.schemas WHERE name = N'${name}') DROP SCHEMA ${quoted(engine, name)}`;
    case "oracle":
      return null;
  }
}

/** Removes a column this product just added, when the catalog refused it. */
export function dropHomeColumnSql(
  engine: SqlSourceEngine,
  schema: string,
  table: string,
  column: string,
): string {
  return `ALTER TABLE ${quoted(engine, schemaOf(schema))}.${quoted(engine, tableOf(table))} DROP COLUMN ${quoted(engine, columnOf(column))}`;
}

/** A column added later to a table AnyGridDB created. */
export function addHomeColumnSql(
  engine: SqlSourceEngine,
  schema: string,
  table: string,
  column: { name: string; fieldType: FieldType },
): string {
  return `ALTER TABLE ${quoted(engine, schemaOf(schema))}.${quoted(engine, tableOf(table))} ADD ${quoted(engine, columnOf(column.name))} ${columnType(engine, column.fieldType)}`;
}
