import { describe, expect, it } from "vitest";
import {
  addHomeColumnSql,
  createHomeSql,
  dropHomeColumnSql,
  createHomeTableSql,
  dropHomeSql,
  dropHomeTableSql,
  homeSchemaName,
} from "./host-sql.js";

describe("a base held in a SQL source", () => {
  it("names a schema from the base id and creates it", () => {
    const schema = homeSchemaName("01a1c9c4-90ed-7f2c-b364-428dbed4bbbc");
    expect(schema).toBe("ag01a1c9c490ed7f2cb364428dbe");
    expect(createHomeSql("postgres", schema)).toBe(`CREATE SCHEMA "${schema}"`);
    expect(createHomeSql("mysql", schema)).toBe(
      `CREATE DATABASE \`${schema}\``,
    );
    expect(createHomeSql("oracle", schema)).toBeNull();
  });

  it("creates a table and a later column in that schema", () => {
    const schema = homeSchemaName("01a1c9c4-90ed-7f2c-b364-428dbed4bbbc");
    const table = `t${"a".repeat(26)}`;
    expect(
      createHomeTableSql("postgres", schema, table, [
        { name: "total", fieldType: "number" },
      ]),
    ).toBe(
      `CREATE TABLE "${schema}"."${table}" ("id" bigint generated by default as identity primary key, "total" numeric)`,
    );
    expect(
      addHomeColumnSql("postgres", schema, table, {
        name: "note",
        fieldType: "long_text",
      }),
    ).toBe(`ALTER TABLE "${schema}"."${table}" ADD "note" text`);
    expect(dropHomeColumnSql("postgres", schema, table, "note")).toBe(
      `ALTER TABLE "${schema}"."${table}" DROP COLUMN "note"`,
    );
  });

  it("drops that schema, and a missing one is not an error", () => {
    const schema = homeSchemaName("01a1c9c4-90ed-7f2c-b364-428dbed4bbbc");
    const table = `t${"b".repeat(26)}`;
    expect(dropHomeSql("postgres", schema)).toBe(
      `DROP SCHEMA IF EXISTS "${schema}" CASCADE`,
    );
    expect(dropHomeSql("sqlserver", schema)).toContain(`[${schema}]`);
    expect(dropHomeTableSql("mysql", schema, table)).toBe(
      `DROP TABLE IF EXISTS \`${schema}\`.\`${table}\``,
    );
    expect(dropHomeSql("oracle", schema)).toBeNull();
  });

  it("refuses a name it did not mint", () => {
    expect(() => createHomeSql("postgres", "public")).toThrow();
    expect(() => createHomeSql("postgres", "Ag")).toThrow();
  });
});
